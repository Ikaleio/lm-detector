import { generateFiles } from 'fumadocs-openapi'
import { openapi } from '../app/lib/openapi.server.ts'

// Sidebar icons of the generated pages, by operation title.
const icons: Record<string, string> = { 'Health check': 'HeartPulse', 'Relay an API request': 'ArrowRightLeft' }

// Regenerates one page per proxy operation from worker/openapi.json. Run after changing the schema.
await generateFiles({
  input: openapi,
  output: './content/docs/reference/proxy-api',
  per: 'operation',
  includeDescription: true,
  frontmatter: title => ({ full: true, icon: icons[title] }),
  addGeneratedComment: 'Generated by `bun run --cwd docs openapi` from worker/openapi.json. Do not edit.',
})
